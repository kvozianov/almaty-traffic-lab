from __future__ import annotations

from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from pathlib import PurePosixPath
import hashlib
import json
import subprocess
from typing import Any, Mapping


CLAIM_LABELS = {"demo", "proxy", "calibrated", "real-data", "procurement-ready"}


@dataclass(slots=True)
class DataSource:
    id: str
    label: str
    path: str
    claim_label: str
    source_type: str
    available: bool
    sha256: str | None = None
    bytes: int | None = None
    freshness: str = "local workspace snapshot"
    notes: str = ""


def build_run_passport(
    *,
    run_id: str,
    scenario_params: dict[str, Any],
    seed: int | None,
    claim_labels: dict[str, str] | None = None,
    data_sources: list[dict[str, Any]] | None = None,
    limitations: list[str] | None = None,
    calibration_path: str | Path = "data/calibration/almaty_calibration_layer.json",
    root: str | Path = ".",
    source_paths: Mapping[str, str | Path] | None = None,
    source_refs: Mapping[str, str] | None = None,
    project_context: Mapping[str, Any] | None = None,
    calibration_context: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a serializable run passport for audit and dossier outputs.

    Legacy callers may rely on ``root`` and ``calibration_path``. A staging
    caller passes the three explicit contexts instead; that mode is closed and
    never fills a missing source or project field from the repository root.
    """

    root_path = Path(root)
    labels = _normalize_claim_labels(
        claim_labels
        or {
            "roads": "real-data",
            "traffic": "demo",
            "analytics": "proxy",
            "calibration": "proxy",
            "dossier": "proxy",
        }
    )
    sources = default_data_sources() if data_sources is None else data_sources
    resolved_sources = _resolve_source_context(
        sources,
        root=root_path,
        source_paths=source_paths,
        source_refs=source_refs,
    )
    source_payload = [
        asdict(
            _source_from_config(
                source,
                root_path,
                physical_path=resolved_sources[str(source.get("id"))][0],
                source_ref=resolved_sources[str(source.get("id"))][1],
            )
        )
        for source in sources
    ]
    model = _project_context(root_path, project_context, explicit_sources=source_paths is not None)
    calibration = _resolved_calibration_context(
        calibration_path=calibration_path,
        calibration_context=calibration_context,
        resolved_sources=resolved_sources,
        explicit_sources=source_paths is not None,
    )
    return {
        "runId": run_id,
        "createdAt": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "model": model,
        "seed": seed,
        "scenarioParams": scenario_params,
        "dataSources": source_payload,
        "calibrationValidation": calibration,
        "limitations": limitations or default_limitations(),
        "claimLabels": labels,
        "audit": {
            "claimRule": "Use demo/proxy/calibrated/real-data/procurement-ready exactly; do not upgrade without evidence.",
            "reproducibility": "Run passport captures seed, git hash, scenario parameters, source fingerprints, limitations, and claim labels.",
        },
    }


def write_run_passport(passport: dict[str, Any], path: str | Path) -> Path:
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(passport, indent=2, ensure_ascii=True), encoding="utf-8")
    return output


