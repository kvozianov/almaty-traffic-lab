def _source_from_config(
    source: dict[str, Any],
    root: Path,
    *,
    physical_path: Path | None = None,
    source_ref: str | None = None,
) -> DataSource:
    label = _claim_label(str(source.get("claim_label", "demo")))
    path = str(source.get("path", ""))
    full_path = physical_path if physical_path is not None else root / path
    serialized_path = source_ref if source_ref is not None else path
    available = full_path.exists()
    if label == "real-data" and not available:
        label = "demo"
    return DataSource(
        id=str(source.get("id", path or "source")),
        label=str(source.get("label", source.get("id", path))),
        path=serialized_path,
        claim_label=label,
        source_type=str(source.get("source_type", "local file")),
        available=available,
        sha256=_sha256(full_path) if available and full_path.is_file() else None,
        bytes=full_path.stat().st_size if available and full_path.is_file() else None,
        freshness=str(source.get("freshness", "local workspace snapshot")),
        notes=str(source.get("notes", "")),
    )


def _normalize_claim_labels(labels: dict[str, str]) -> dict[str, str]:
    return {str(key): _claim_label(str(value)) for key, value in labels.items()}


def _claim_label(value: str) -> str:
    if value not in CLAIM_LABELS:
        raise ValueError(f"Unsupported claim label: {value}. Expected one of {sorted(CLAIM_LABELS)}")
    return value


def _calibration_validation(
    path: str | Path,
    *,
    display_path: str | None = None,
) -> dict[str, Any]:
    calibration_path = Path(path)
    serialized_path = display_path if display_path is not None else str(calibration_path)
    if not calibration_path.exists():
        return {
            "claimLabel": "demo",
            "path": serialized_path,
            "available": False,
            "notes": "Calibration layer file not found.",
            "observedVsSimulated": [],
        }
    payload = json.loads(calibration_path.read_text(encoding="utf-8"))
    return {
        "claimLabel": "proxy",
        "path": serialized_path,
        "available": True,
        "segmentCount": len(payload.get("segments", [])),
        "intersectionCount": len(payload.get("must_calibrate_intersections", [])),
        "observedVsSimulated": [],
        "notes": "Calibration layer contains corridor and intersection assumptions; per-run observed-vs-simulated rows remain a limitation until attached.",
    }


def _resolve_source_context(
    sources: list[dict[str, Any]],
    *,
    root: Path,
    source_paths: Mapping[str, str | Path] | None,
    source_refs: Mapping[str, str] | None,
) -> dict[str, tuple[Path, str]]:
    source_ids = [str(source.get("id", "")) for source in sources]
    if any(not source_id for source_id in source_ids) or len(source_ids) != len(set(source_ids)):
        raise ValueError("Every data source must have one unique non-empty id")
    expected = set(source_ids)
    if source_paths is None:
        if source_refs is not None:
            raise ValueError("source_paths is required when source_refs is explicit")
        return {
            source_id: (root / str(source.get("path", "")), str(source.get("path", "")))
            for source_id, source in zip(source_ids, sources, strict=True)
        }

    _require_exact_roles(source_paths, expected, map_name="source_paths")
    if source_refs is None:
        raise ValueError("source_refs is required when source_paths is explicit")
    _require_exact_roles(source_refs, expected, map_name="source_refs")
    return {
        source_id: (
            Path(source_paths[source_id]),
            _logical_ref(source_refs[source_id], role=source_id),
        )
        for source_id in source_ids
    }


def _project_context(
    root: Path,
    context: Mapping[str, Any] | None,
    *,
    explicit_sources: bool,
) -> dict[str, Any]:
    if context is None:
        if explicit_sources:
            raise ValueError("project_context is required when source_paths is explicit")
        return {
            "name": "traffic-sim-almaty",
            "version": _project_version(root),
            "gitHash": _git_hash(root),
        }
    required = {"name", "version", "gitHash"}
    missing = sorted(required - set(context))
    if missing:
        raise ValueError(f"Invalid project_context: missing={missing}")
    return {
        "name": str(context["name"]),
        "version": str(context["version"]),
        "gitHash": None if context["gitHash"] is None else str(context["gitHash"]),
    }


def _resolved_calibration_context(
    *,
    calibration_path: str | Path,
    calibration_context: Mapping[str, Any] | None,
    resolved_sources: Mapping[str, tuple[Path, str]],
    explicit_sources: bool,
) -> dict[str, Any]:
    if calibration_context is not None:
        required = {"claimLabel", "path", "available", "observedVsSimulated", "notes"}
        missing = sorted(required - set(calibration_context))
        if missing:
            raise ValueError(f"Invalid calibration_context: missing={missing}")
        payload = dict(calibration_context)
        payload["claimLabel"] = _claim_label(str(payload["claimLabel"]))
        payload["path"] = _logical_ref(str(payload["path"]), role="calibration")
        payload["available"] = bool(payload["available"])
        if not isinstance(payload["observedVsSimulated"], list):
            raise ValueError("calibration_context.observedVsSimulated must be a list")
        return payload

    if explicit_sources:
        calibration_source = resolved_sources.get("calibration-layer")
        if calibration_source is None:
            raise ValueError(
                "calibration_context is required when explicit sources omit calibration-layer"
            )
        return _calibration_validation(
            calibration_source[0],
            display_path=calibration_source[1],
        )
    return _calibration_validation(calibration_path)


def _require_exact_roles(
    values: Mapping[str, object],
    expected: set[str],
    *,
    map_name: str,
) -> None:
    actual = set(values)
    missing = sorted(expected - actual)
    unknown = sorted(actual - expected)
    if missing or unknown:
        raise ValueError(f"Invalid {map_name}: missing={missing}, unknown={unknown}")


def _logical_ref(value: str, *, role: str) -> str:
    raw = str(value)
    path = PurePosixPath(raw)
    if (
        not raw
        or raw != raw.strip()
        or "\\" in raw
        or path.is_absolute()
        or ".." in path.parts
        or any(".staging" in part for part in path.parts)
        or (path.parts and path.parts[0].endswith(":"))
        or path.as_posix() != raw
    ):
        raise ValueError(f"Unsafe logical reference for {role}: {raw!r}")
    return path.as_posix()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _git_hash(root: Path) -> str | None:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (subprocess.CalledProcessError, OSError):
        return None
    return result.stdout.strip() or None


def _project_version(root: Path) -> str:
    pyproject = root / "pyproject.toml"
    if not pyproject.exists():
        return "unknown"
    for line in pyproject.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("version"):
            return line.split("=", 1)[1].strip().strip('"')
    return "unknown"
